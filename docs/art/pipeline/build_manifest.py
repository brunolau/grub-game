def keys(prefix, kind=None):
    return sorted(k for k, v in R.items() if k.startswith(prefix) and (kind is None or v.get("kind") == kind))


def rng(fr):
    fr = list(fr)
    if len(fr) == 1:
        return str(fr[0])
    if fr == list(range(fr[0], fr[-1] + 1)):
        return "%d-%d" % (fr[0], fr[-1])
    return ",".join(str(f) for f in fr)


def anims(v):
    items = sorted(v.get("anims", {}).items(), key=lambda kv: kv[1]["frames"][0])
    return "; ".join("**%s** %s @%s fps %s" % (n, rng(a["frames"]), a["fps"], "loop" if a["loop"] else "once") for n, a in items)


def sz(v):
    return "%dx%d" % tuple(v["size"])


def fr(v):
    return "%dx%d" % tuple(v["frame"])


def gr(v):
    return "%dx%d" % tuple(v["grid"])


def pv(v):
    return "(%d, %d)" % tuple(v["pivot"]) if "pivot" in v else "-"


def table(head, rows):
    W("| " + " | ".join(head) + " |")
    W("|" + "|".join("---" for _ in head) + "|")
    for r in rows:
        W("| " + " | ".join(str(c).replace("|", "/") for c in r) + " |")
    W("")


def short(k):
    return "`" + k[len("assets/"):] + "`"


def pal(rel, n=6):
    im = load(os.path.join(ROOT, *rel.split("/")))
    return " ".join("`%s`" % c for c, _ in palette(im, n))


