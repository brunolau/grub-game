def actor_section(title, prefix, kind, intro):
    W("## " + title)
    W("")
    W(intro)
    W("")
    ks = [k for k in keys(prefix) if R[k]["kind"] == kind]
    rows = []
    for k in ks:
        v = R[k]
        rows.append([short(k), sz(v), fr(v), gr(v), pv(v), v["facing"], ("%dx%d" % tuple(v["body_box_logical"])) if "body_box_logical" in v else "-", v.get("note", "")])
    table(["File", "Size", "Frame", "Grid", "Pivot", "Facing", "Body box (logical w x h)", "Role / notes"], rows)
    W("Animations (frame indices, fps, loop):")
    W("")
    for k in ks:
        v = R[k]
        base = k[:-4]
        if base.endswith("_b") and (base[:-2] + ".png") in R:
            continue
        twin = " (same for `%s`)" % (os.path.basename(base) + "_b.png") if (base + "_b.png") in R else ""
        W("- %s%s: %s" % (short(k), twin, anims(v)))
    W("")


